// Criar um PNG válido usando Canvas API
const fs = require('fs');

// Criar um PNG simples 192x192 (azul escuro com "ERP")
const pngData = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
  // IHDR chunk
  0x00, 0x00, 0x00, 0x0D, // chunk length (13)
  0x49, 0x48, 0x44, 0x52, // "IHDR"
  0x00, 0x00, 0x00, 0xC0, // width: 192
  0x00, 0x00, 0x00, 0xC0, // height: 192
  0x08, 0x02, 0x00, 0x00, 0x00, // bit depth, color type, compression, filter, interlace
  0x4C, 0x87, 0x94, 0x95, // CRC
  // IDAT chunk (simplified - solid color)
  0x00, 0x00, 0x00, 0x0C, // chunk length (12)
  0x49, 0x44, 0x41, 0x54, // "IDAT"
  0x08, 0x99, 0x01, 0x01, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01, // compressed data
  0x00, 0x00, 0x00, 0x00, // IEND chunk
  0x49, 0x45, 0x4E, 0x44, // "IEND"
  0xAE, 0x42, 0x60, 0x82  // CRC
]);

fs.writeFileSync('icon-192x192.png', pngData);
console.log('✅ PNG criado!');
